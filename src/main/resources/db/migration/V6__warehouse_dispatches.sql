CREATE TABLE warehouse_dispatch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_request_id BIGINT NOT NULL UNIQUE REFERENCES ingredient_request(id) ON DELETE RESTRICT,
    prepared_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    dispatched_at TIMESTAMP NOT NULL,
    note VARCHAR(1000),
    CONSTRAINT uq_warehouse_dispatch_request UNIQUE (ingredient_request_id)
);

CREATE TABLE warehouse_dispatch_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_dispatch_id BIGINT NOT NULL REFERENCES warehouse_dispatch(id) ON DELETE CASCADE,
    ingredient_id BIGINT NOT NULL REFERENCES ingredient(id) ON DELETE RESTRICT,
    approved_quantity NUMERIC(15, 3) NOT NULL,
    dispatched_quantity NUMERIC(15, 3) NOT NULL,
    CONSTRAINT uq_warehouse_dispatch_item_ingredient UNIQUE (warehouse_dispatch_id, ingredient_id),
    CONSTRAINT chk_warehouse_dispatch_item_quantity CHECK (
        approved_quantity > 0 AND dispatched_quantity > 0 AND dispatched_quantity <= approved_quantity
    )
);

CREATE INDEX idx_warehouse_dispatch_dispatched_at ON warehouse_dispatch (dispatched_at DESC);
